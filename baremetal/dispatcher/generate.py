#!/usr/bin/env python3
"""Assemble dispatcher instructions into a build directory, optionally with a test kernel."""
import importlib.util
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("atlas_assembler", HERE.parent / "assembler.py")
assembler = importlib.util.module_from_spec(spec)
spec.loader.exec_module(assembler)

def render(source, symbol):
    words = assembler.assemble(source.read_text())
    if symbol == "atlas_dispatcher_image":
        assert len(words) <= 256, "Dispatcher exceeds its resident region"
    guard = symbol.upper() + "_H"
    lines = [f"/* Generated by generate.py; edit {source.name} instead. */",
             f"#ifndef {guard}", f"#define {guard}",
             "#include <stdint.h>", f"static const uint32_t {symbol}[] = {{"]
    lines += [f"    0x{word:08x}U," for word in words]
    return "\n".join(lines + ["};", "#endif", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, required=True,
                        help="Build directory for generated headers")
    parser.add_argument("--test-kernel", type=Path,
                        help="Optionally assemble a test kernel into test_kernel_image.h")
    args = parser.parse_args()
    output = args.out_dir
    output.mkdir(parents=True, exist_ok=True)
    (output / "dispatcher_image.h").write_text(render(HERE / "dispatcher.S", "atlas_dispatcher_image"))
    if args.test_kernel:
        (output / "test_kernel_image.h").write_text(render(args.test_kernel, "atlas_test_kernel"))
